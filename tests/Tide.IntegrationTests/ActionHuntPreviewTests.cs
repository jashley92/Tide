namespace Tide.IntegrationTests;

/// <summary>
/// A sweep's or hunt's query previewed when its page opens: shown to whoever may work it, with nothing saved or logged
/// until they copy or keep it, and the result buttons held back until a saved query exists.
/// </summary>
public class ActionHuntPreviewTests(TideApp app) : IClassFixture<TideApp>
{
    private static readonly SignIn Outsider = new("dev:preview-outsider", "Omar Outsider", "ActionOwner");
    private static readonly SignIn Viewer = new("dev:preview-viewer", "Viewer", "Viewer");

    private async Task<T> As<T>(Func<IServiceProvider, Task<T>> what, SignIn? who = null)
    {
        await using var scope = SignedIn(app, who ?? SignIn.Analyst);
        return await what(scope.ServiceProvider);
    }

    /// <summary>An action of <paramref name="kind"/> raised from an article with one IP indicator; its number and id.</summary>
    private Task<(int Number, Guid Id)> Raise(string title, ActionKind kind = ActionKind.IocSweep, string ip = "203.0.113.45") => As(async sp =>
    {
        var articles = sp.GetRequiredService<ArticleService>();
        var actions = sp.GetRequiredService<ActionService>();
        var article = await articles.CreateAsync(title + " (article)", "Vendor", null, TlpLevel.Clear);
        var form = ArticleForm.From((await articles.GetAsync(article))!);
        form.Bluf = "Exploited.";
        form.Indicators = [new() { Type = IndicatorType.IpAddress, Value = ip }];
        await articles.SaveAsync(form);
        var team = await sp.GetRequiredService<TeamService>().AddAsync(title + " team", null, null);
        var number = await actions.CreateAsync(new ActionForm { Title = title, Kind = kind, TeamId = team, ArticleId = article });
        return (number, (await actions.GetAsync(number))!.Action.Id);
    });

    /// <summary>What a page view must leave alone: the action's hunt queries and history, and the audit log.</summary>
    private Task<(int Hunts, int Events, int Audit)> Trace(Guid id) => As(async sp =>
    {
        await using var db = await sp.GetRequiredService<IAppDbContextFactory>().CreateAsync();
        return (await db.HuntQueries.CountAsync(h => h.ActionId == id), await db.ActionEvents.CountAsync(e => e.ActionId == id), await db.AuditLog.CountAsync());
    });

    private Task<ActionItem> Read(int number) => As(async sp => (await sp.GetRequiredService<ActionService>().GetAsync(number))!.Action);

    private Task<Rendered<ActionPage>> Open(int number, SignIn? who = null) =>
        RenderAsync<ActionPage>(app, "/actions/" + number, new() { ["Number"] = (int?)number }, who);

    // The button that says label, from its opening tag.
    private static string Button(string html, string label)
    {
        var at = html.IndexOf(label, StringComparison.Ordinal);
        at.Should().BePositive($"the page has {label}");
        return html[html.LastIndexOf("<button", at, StringComparison.Ordinal)..at];
    }

    [Fact]
    public async Task OpeningASweep_ShowsItsQueryAsAPreview_AndSavesAndLogsNothing()
    {
        var (number, id) = await Raise("Preview sweep on open");
        var before = await Trace(id);

        await using var page = await Open(number);
        var html = WebUtility.HtmlDecode(await page.Html());

        html.Should().Contain("<pre id=\"hunt-preview\" class=\"tide-query\"").And.Contain("203.0.113.45").And.Contain("Generated by TIDE from 1 indicator")
            .And.Contain("Preview</span>").And.Contain("aria-label=\"Query language\"");
        Button(html, " Copy</button>").Should().Contain("data-copy-target=\"hunt-preview\"").And.Contain("data-copy-status=\"hunt-preview-status\"")
            .And.Contain("data-copy-done=\"Copied. The query is now on the action.\"").And.NotContain("disabled");
        html.Should().Contain("Keep this query</button>").And.NotContain("Generate from 1 indicator</button>", "the preview is that query already");
        html.IndexOf("id=\"hunt-preview\"", StringComparison.Ordinal).Should().BeLessThan(html.IndexOf("id=\"feed-h\"", StringComparison.Ordinal));
        (await Trace(id)).Should().Be(before, "viewing the page writes nothing: no hunt query, no history line, no audit entry");
        before.Hunts.Should().Be(0);
    }

    [Fact]
    public async Task TheResultButtons_AreDisabledWithAReason_UntilASavedQueryExists()
    {
        var (number, _) = await Raise("Preview sweep results");
        await using var page = await Open(number);
        var html = WebUtility.HtmlDecode(await page.Html());

        Button(html, " No hits, close</button>").Should().Contain("disabled").And.Contain("aria-describedby=\"hunt-preview-why\"");
        Button(html, " Record hits</button>").Should().Contain("disabled").And.Contain("aria-describedby=\"hunt-preview-why\"");
        html.Should().Contain("<span id=\"hunt-preview-why\" class=\"small tide-muted\">Copy or keep the query first.</span>");

        await page.Click(p => p.Drawer!.Hunt!.KeepPreview());
        html = WebUtility.HtmlDecode(await page.Html());
        html.Should().NotContain("id=\"hunt-preview\"").And.NotContain("Record hits").And.Contain(" Record the result</button>");
        Button(html, " Record the result</button>").Should().NotContain("disabled");
        html.Should().Contain("Copy the query and run it first.", "kept, not copied: closing clean still asks for the copy, as a generated query does");
        Toasts(page).Select(t => t.Message).Should().Equal("Query kept on the action.");
        // Nobody has it, and the Next line doesn't hide that a query is now on it.
        page.Component.Next!.Kind.Should().Be(NextKind.Unowned);
        html.Should().Contain("Nobody has it yet. Take it, then run the query that's on the action.");
    }

    private static IReadOnlyList<Tide.Web.Services.ToastService.Toast> Toasts<T>(Rendered<T> r) =>
        r.Scope.ServiceProvider.GetRequiredService<Tide.Web.Services.ToastService>().Toasts;

    [Fact]
    public async Task Copy_SavesThePreviewOnce_WithOneHistoryLine_AndTheQueryCountsAsCopied()
    {
        var (number, id) = await Raise("Preview sweep copy");
        var before = await Trace(id);
        await using var page = await Open(number);
        var shown = page.Component.Drawer!.Hunt!.Preview;
        shown.Should().NotBeNull();

        await page.Click(p => p.Drawer!.Hunt!.CopyPreview());

        var after = await Trace(id);
        (after.Hunts, after.Events - before.Events).Should().Be((1, 1), "one query, one line of history");
        var action = await Read(number);
        var hunt = action.Hunts.Should().ContainSingle().Subject;
        var language = QueryDialects.All[0];
        (hunt.Text, hunt.GeneratedText, hunt.Dialect, hunt.Result).Should().Be((shown, shown, language.Key, HuntResult.NotRun), "what was copied is what's kept");
        action.Events.Should().Contain(e => e.Text == $"Generated a {language.Name} hunt query.");

        var html = WebUtility.HtmlDecode(await page.Html());
        // Copied here, and its days start from the window the query names, so "No hits, close" is one click away.
        html.Should().NotContain("id=\"hunt-preview\"").And.NotContain("Copy the query and run it first.", "it was copied here")
            .And.Contain("class=\"tide-hunt-close\"").And.NotContain("Say how many days it searched.");
        shown.Should().Contain("set it to the last 30 days", "this language's query leaves the range to the console, and says which");
        html.Should().Contain("class=\"form-control form-control-sm tide-w-count\" value=\"30\"");
        Button(html, " No hits, close").Should().NotContain("aria-describedby", "nothing is left to say before it can be pressed");
        // One confirmation: the browser's, beside the query (it knows the copy worked). No toast as well.
        Toasts(page).Should().BeEmpty();

        // A second click (the preview has gone by then) adds nothing.
        await page.Click(p => p.Drawer!.Hunt!.CopyPreview());
        (await Trace(id)).Should().Be(after);
    }

    [Fact]
    public async Task ThePreview_IsTheSameTextGenerateSaves_InEveryLanguage()
    {
        // A value with the characters a query language quotes with: the preview is written by the builder Generate uses.
        var (_, id) = await Raise("Preview sweep languages", ip: "198.51.100.9");
        await As(async sp =>
        {
            await sp.GetRequiredService<ActionService>().AddIndicatorsAsync(id, [new IndicatorForm { Type = IndicatorType.FileName, Value = "it's \"odd\\name\".exe" }]);
            return true;
        });
        foreach (var d in QueryDialects.All)
        {
            var (preview, saved) = await As(async sp =>
            {
                var actions = sp.GetRequiredService<ActionService>();
                return (await actions.PreviewHuntAsync(id, d.Key), (await actions.GenerateHuntAsync(id, d.Key)).Text);
            });
            preview.Should().Be(saved, $"the {d.Name} preview and the saved query come from one builder");
        }
    }

    [Fact]
    public async Task SomeoneWhoCantWorkTheAction_SeesNoPreview_AndTheServiceRefusesThem()
    {
        var (number, id) = await Raise("Preview sweep outsiders");
        foreach (var who in new[] { Viewer, Outsider })
        {
            await using var page = await Open(number, who);
            var html = await page.Html();
            html.Should().Contain("Preview sweep outsiders").And.NotContain("id=\"hunt-preview\"").And.NotContain("203.0.113.45")
                .And.NotContain("Keep this query").And.NotContain("aria-label=\"Query language\"");
            await FluentActions.Invoking(() => As(sp => sp.GetRequiredService<ActionService>().PreviewHuntAsync(id, "kql"), who))
                .Should().ThrowAsync<ForbiddenException>();
        }
        (await Trace(id)).Hunts.Should().Be(0);
    }

    [Fact]
    public async Task OnlyAnOpenSweepOrHuntWithIndicatorsAndNoQuery_HasAPreview()
    {
        // Another kind keeps Generate, as before.
        var (block, _) = await Raise("Preview block", ActionKind.Block);
        await using (var page = await RenderAsync<ActionPage>(app, $"/actions/{block}?tool=hunt", new() { ["Number"] = (int?)block }))
            (await page.Html()).Should().NotContain("id=\"hunt-preview\"");

        // A hunt has one, as a sweep does.
        var (hunt, huntId) = await Raise("Preview hunt", ActionKind.ThreatHunt);
        await using (var page = await Open(hunt))
            (await page.Html()).Should().Contain("id=\"hunt-preview\"");

        // With a query already (a hand-written one), it's the page as before: Generate offered, no preview.
        await As(async sp => { await sp.GetRequiredService<ActionService>().AddHandWrittenHuntAsync(huntId, "kql", "DeviceProcessEvents"); return true; });
        await using (var page = await Open(hunt))
            (await page.Html()).Should().NotContain("id=\"hunt-preview\"").And.Contain("Generate from 1 indicator</button>");

        // No indicators: nothing to preview.
        var bare = await As(async sp =>
        {
            var team = await sp.GetRequiredService<TeamService>().AddAsync("Preview bare team", null, null);
            return await sp.GetRequiredService<ActionService>().CreateAsync(new ActionForm { Title = "Preview bare sweep", Kind = ActionKind.IocSweep, TeamId = team });
        });
        await using (var page = await Open(bare))
            (await page.Html()).Should().NotContain("id=\"hunt-preview\"").And.Contain("there are no indicators yet");
    }

    [Fact]
    public async Task TheNextLine_FollowsTheSweep_NobodyHasIt_ThenYoursToRun_ThenASavedQueryAwaitingItsResult_AlsoAfterAReload()
    {
        var (number, id) = await Raise("Preview sweep next");
        await using (var page = await Open(number))
        {
            page.Component.Next!.Kind.Should().Be(NextKind.Unowned);
            WebUtility.HtmlDecode(await page.Html()).Should().Contain("data-next=\"Unowned\"").And.Contain("Nobody has it yet.").And.Contain("Take it</button>");
            System.Text.RegularExpressions.Regex.Matches(await page.Html(), "class=\"tide-next\"").Should().HaveCount(1, "one Next line");
        }

        await As(async sp => { await sp.GetRequiredService<ActionService>().TakeAsync(id); return true; });
        var before = await Trace(id);
        await using (var page = await Open(number))
        {
            page.Component.Next!.Kind.Should().Be(NextKind.RunQuery);
            (await page.Html()).Should().Contain("Copy the query and run it in your SIEM.");
            (await Trace(id)).Should().Be(before);

            await page.Click(p => p.Drawer!.Hunt!.CopyPreview());
            page.Component.Next!.Kind.Should().Be(NextKind.AwaitingResult);
            WebUtility.HtmlDecode(await page.Html()).Should().Contain("data-next=\"AwaitingResult\"").And.Contain("Run the query that's on the action, then record what it found.");
        }
        // The saved query is what the line goes by, so the page opened again says the same.
        await using (var page = await Open(number))
        {
            page.Component.Next!.Kind.Should().Be(NextKind.AwaitingResult);
            WebUtility.HtmlDecode(await page.Html()).Should().Contain("Run the query that's on the action, then record what it found.").And.NotContain("Copy the query and run it in your SIEM.");
        }

        // Its result recorded: the query is no longer what's next.
        var hunt = (await Read(number)).Hunts.Single();
        await As(async sp => { await sp.GetRequiredService<ActionService>().RecordHuntResultAsync(hunt.Id, HuntResult.Hits, 2, null, null); return true; });
        await using (var page = await Open(number))
            page.Component.Next.Should().BeNull();
    }
}
