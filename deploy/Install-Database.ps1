#Requires -Version 5.1

<#
.SYNOPSIS
    Provisions the Tide SQL Server 2022 database and the app-pool login (Windows auth).

.DESCRIPTION
    Wraps deploy/sql/01-Create-Database.sql. Creates the database (FULL recovery,
    RCSI on) and a least-privilege login/user for the IIS application-pool identity.
    Integrated authentication only - no SQL credentials are created or stored.

    Run on (or with line-of-sight to) the SQL Server, as an account that is sysadmin
    on the target instance. Idempotent - safe to re-run.

    Values can come from an answers file (-ConfigFile tide.config.psd1, generated by
    the template) OR as parameters. A parameter you pass explicitly overrides
    the file.

.PARAMETER ConfigFile
    Path to a tide.config.psd1 answers file (see tide.config.template.psd1). Fills
    any parameter you don't pass explicitly. Optional - you can pass everything as parameters.

.PARAMETER SqlInstance
    Target instance, e.g. "SQLHOST" or "SQLHOST\INSTANCE". Required (parameter or config file).

.PARAMETER AppAccount
    Windows account the Tide IIS app pool runs as. For a gMSA include the
    trailing '$', e.g. "CONTOSO\svc-tide$". Must already exist in AD.

.PARAMETER DbName
    Database name. Default: Tide.

.PARAMETER DataPath / LogPath
    Optional explicit folders for the data/log files. Omit to use instance defaults.

.PARAMETER SchemaMode
    AppMigrates (default) - grant db_owner; the app applies EF migrations at startup.
    DbaApplies             - grant datareader/datawriter/EXECUTE only; a DBA applies
                             the schema. Combine with -ApplySchema to run it now.

.PARAMETER BackupAccount
    Optional. The Windows account the backup tasks (Backup-Tide.ps1, Test-TideRestore.ps1) run as: a gMSA with its
    trailing '$', or for tasks that run as SYSTEM the web server's computer account (CONTOSO\WEB01$). It's given what
    they need and no more (deploy/sql/02-Grant-Backup.sql): db_backupoperator in the database, dbcreator on the server
    (RESTORE VERIFYONLY and the drill's restore) and SELECT on msdb.dbo.backupset. Needs sysadmin to run.

.PARAMETER ApplySchema
    When SchemaMode=DbaApplies, also execute deploy/sql/tide-schema-sqlserver.sql
    against the database (as the sysadmin running this script).

.PARAMETER ValidateServerCertificate
    Check the SQL Server's TLS certificate (it must chain to a root this machine trusts and name the instance's host).
    Off by default, as most instances use a self-signed certificate: the connection is still encrypted, but who it's
    with isn't checked. Also read from the answers file (ValidateServerCertificate = $true).

.EXAMPLE
    .\Install-Database.ps1 -ConfigFile .\tide.config.psd1

.EXAMPLE
    .\Install-Database.ps1 -SqlInstance SQLHOST\PROD -AppAccount "CONTOSO\svc-tide$"
#>
[CmdletBinding()]
param(
    [string] $ConfigFile,
    [string] $SqlInstance,
    [string] $AppAccount,
    [string] $DbName,
    [string] $DataPath,
    [string] $LogPath,
    [ValidateSet('AppMigrates','DbaApplies')] [string] $SchemaMode,
    [string] $BackupAccount,
    [switch] $ApplySchema,
    [switch] $ValidateServerCertificate
)

$ErrorActionPreference = 'Stop'

# --- Merge an optional answers file (explicit -Params win) --------------------
if ($ConfigFile) {
    if (-not (Test-Path $ConfigFile)) { throw "Config file not found: $ConfigFile" }
    $cfg = Import-PowerShellDataFile -Path $ConfigFile
    foreach ($name in 'SqlInstance','AppAccount','DbName','DataPath','LogPath','SchemaMode','BackupAccount') {
        if (-not $PSBoundParameters.ContainsKey($name) -and $cfg.ContainsKey($name) -and "$($cfg[$name])" -ne '') {
            Set-Variable -Name $name -Value $cfg[$name]
        }
    }
}
# A switch in the answers file: $true or $false (or the words), anything else is refused rather than guessed at.
if ($ConfigFile -and -not $PSBoundParameters.ContainsKey('ValidateServerCertificate') -and $cfg.ContainsKey('ValidateServerCertificate')) {
    $v = "$($cfg['ValidateServerCertificate'])".Trim()
    if ($v -notin 'True', 'False', '') { throw "ValidateServerCertificate in $ConfigFile must be `$true or `$false; got '$v'." }
    $ValidateServerCertificate = [switch]($v -eq 'True')
}
# Defaults for anything still unset (built-in default is the lowest precedence).
if (-not $DbName)        { $DbName = 'Tide' }
if ($null -eq $DataPath) { $DataPath = '' }
if ($null -eq $LogPath)  { $LogPath  = '' }
if (-not $SchemaMode)    { $SchemaMode = 'AppMigrates' }
# Required, whichever source they came from.
$missing = @()
if (-not $SqlInstance) { $missing += 'SqlInstance' }
if (-not $AppAccount)  { $missing += 'AppAccount' }
if ($missing.Count) {
    throw "Missing required value(s): $($missing -join ', '). Pass as a -Parameter or set them in -ConfigFile (see tide.config.template.psd1)."
}
# These go into the SQL script as sqlcmd variables, inside [...] and N'...', so a bracket, a quote or a control character
# would change the statement rather than name the database or the account.
if ($DbName -notmatch '^[A-Za-z0-9_\-]{1,128}$') { throw "DbName must be letters, digits, '_' and '-' (such as 'Tide'); got '$DbName'." }
if ($AppAccount -match "[\[\]'`";\p{Cc}]" -or $AppAccount.Length -gt 128) {
    throw "AppAccount must be an account name such as CONTOSO\svc-tide`$ (no brackets, quotes or semicolons); got '$AppAccount'."
}
if ($BackupAccount -and ($BackupAccount -match "[\[\]'`";\p{Cc}]" -or $BackupAccount.Length -gt 128)) {
    throw "BackupAccount must be an account name such as CONTOSO\svc-tide-bk`$ (no brackets, quotes or semicolons); got '$BackupAccount'."
}
foreach ($p in @(@('DataPath', $DataPath), @('LogPath', $LogPath))) {
    if ($p[1] -match "['\p{Cc}]") { throw "$($p[0]) can't contain a quote or a control character; got '$($p[1])'." }
}
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$createSql = Join-Path $scriptDir 'sql\01-Create-Database.sql'
$backupSql = Join-Path $scriptDir 'sql\02-Grant-Backup.sql'
$schemaSql = Join-Path $scriptDir 'sql\tide-schema-sqlserver.sql'

if (-not (Test-Path $createSql)) { throw "Missing $createSql" }

# Whether the instance's certificate is checked: Invoke-Sqlcmd's -TrustServerCertificate and sqlcmd's -C skip it.
$trustCert = -not $ValidateServerCertificate
$sqlcmdTrust = @(if ($trustCert) { '-C' })

# Pick an execution engine: prefer the SqlServer module's Invoke-Sqlcmd, fall back to sqlcmd.exe. Which Invoke-Sqlcmd
# it is matters: SQL Server setup puts the old SQLPS module on the SQL host, whose Invoke-Sqlcmd (like SqlServer's before
# 22) has no -TrustServerCertificate and doesn't encrypt unless told to. Each is given only the parameters it takes, for
# a connection that's encrypted, and checks the certificate when asked to. One that can't do that isn't used.
$useModule = $false
$moduleTls = @{}
$sqlcmdCmd = Get-Command Invoke-Sqlcmd -ErrorAction SilentlyContinue
if ($sqlcmdCmd) {
    $has = $sqlcmdCmd.Parameters
    if ($has.ContainsKey('Encrypt') -and $has.ContainsKey('TrustServerCertificate')) {
        $useModule = $true; $moduleTls = @{ TrustServerCertificate = $trustCert }   # SqlServer 22+: encrypts by default
    } elseif ($has.ContainsKey('EncryptConnection') -and $has.ContainsKey('TrustServerCertificate')) {
        $useModule = $true; $moduleTls = @{ EncryptConnection = $true; TrustServerCertificate = $trustCert }
    } elseif ($has.ContainsKey('EncryptConnection') -and -not $trustCert) {
        $useModule = $true; $moduleTls = @{ EncryptConnection = $true }   # encrypts and checks the certificate
    }
}
$from = if ($sqlcmdCmd -and $sqlcmdCmd.Source) { " (from $("$($sqlcmdCmd.Source) $($sqlcmdCmd.Version)".Trim()))" } else { '' }
$cant = if ($trustCert) { "can't encrypt the connection without checking the SQL Server's certificate" } else { "can't encrypt the connection" }
if (-not $useModule -and -not (Get-Command sqlcmd.exe -ErrorAction SilentlyContinue)) {
    if ($sqlcmdCmd) {
        throw ("The Invoke-Sqlcmd here$from $cant, and sqlcmd.exe isn't available. Install the SqlServer module " +
               "(22 or later):  Install-Module SqlServer -Scope CurrentUser   or install sqlcmd" +
               $(if ($trustCert) { ", or pass -ValidateServerCertificate if this machine trusts the instance's certificate" }) +
               ". Nothing was changed.")
    }
    throw "Neither the SqlServer PowerShell module (Invoke-Sqlcmd) nor sqlcmd.exe is available. " +
          "Install with:  Install-Module SqlServer -Scope CurrentUser"
}
if ($sqlcmdCmd -and -not $useModule) { Write-Host "    The Invoke-Sqlcmd here$from $cant`: using sqlcmd.exe." -ForegroundColor Gray }

function Invoke-Sql {
    param([string] $InputFile, [hashtable] $Vars, [switch] $NoDbVars)
    if ($useModule) {
        $varArray = $Vars.GetEnumerator() | ForEach-Object { "$($_.Key)=$($_.Value)" }
        # -AbortOnError: Invoke-Sqlcmd ignores the script's ":on error exit", so without it a failed step (no
        # permission, say) was reported and the script carried on, printing success lines for things not done.
        Invoke-Sqlcmd -ServerInstance $SqlInstance -InputFile $InputFile -Variable $varArray `
                      @moduleTls -QueryTimeout 0 -OutputSqlErrors $true -AbortOnError -ErrorAction Stop -Verbose
    } else {
        $varArgs = @()
        foreach ($k in $Vars.Keys) { $varArgs += @('-v', ("{0}={1}" -f $k, $Vars[$k])) }
        & sqlcmd.exe -S $SqlInstance -E -b @sqlcmdTrust -I -i $InputFile @varArgs   # -I: QUOTED_IDENTIFIER on, which filtered indexes need
        if ($LASTEXITCODE -ne 0) { throw "sqlcmd failed (exit $LASTEXITCODE) on $InputFile" }
    }
}

Write-Host "==> Provisioning database [$DbName] on [$SqlInstance] for [$AppAccount] (mode: $SchemaMode)" -ForegroundColor Cyan

# --- Preflight: does the account running this have the rights for what's still to do? ---------------------
# Creating the database needs CREATE ANY DATABASE (dbcreator), the server login ALTER ANY LOGIN (securityadmin),
# and the database user and its roles control of the database (its owner has that, so it follows from creating it).
# sysadmin has all of it. Checked first so a missing right stops here, before anything is half done.
$preflight = @"
SET NOCOUNT ON;
SELECT SUSER_SNAME() AS RunAs,
       IS_SRVROLEMEMBER('sysadmin') AS IsSysadmin,
       HAS_PERMS_BY_NAME(NULL, NULL, 'CREATE ANY DATABASE') AS CanCreateDb,
       HAS_PERMS_BY_NAME(NULL, NULL, 'ALTER ANY LOGIN') AS CanCreateLogin,
       CASE WHEN DB_ID(N'$($DbName -replace "'", "''")') IS NULL THEN 0 ELSE 1 END AS DbExists,
       CASE WHEN SUSER_ID(N'$($AppAccount -replace "'", "''")') IS NULL THEN 0 ELSE 1 END AS LoginExists,
       ISNULL(HAS_PERMS_BY_NAME(N'$($DbName -replace "'", "''")', 'DATABASE', 'CONTROL'), 0) AS ControlsDb;
"@
if ($useModule) {
    $p = Invoke-Sqlcmd -ServerInstance $SqlInstance -Query $preflight @moduleTls -AbortOnError -ErrorAction Stop
} else {
    $line = (& sqlcmd.exe -S $SqlInstance -E -b @sqlcmdTrust -h -1 -W -s '|' -Q $preflight) | Where-Object { $_ -match '\|' } | Select-Object -First 1
    if ($LASTEXITCODE -ne 0 -or -not $line) { throw "Couldn't connect to [$SqlInstance] to check permissions (sqlcmd exit $LASTEXITCODE)." }
    $f = $line.Split('|')
    $p = [pscustomobject]@{ RunAs = $f[0]; IsSysadmin = [int]$f[1]; CanCreateDb = [int]$f[2]; CanCreateLogin = [int]$f[3]
                            DbExists = [int]$f[4]; LoginExists = [int]$f[5]; ControlsDb = [int]$f[6] }
}
$lacking = @()
if ([int]$p.IsSysadmin -ne 1) {
    if ([int]$p.DbExists -eq 0 -and [int]$p.CanCreateDb -ne 1) { $lacking += "create the database [$DbName] (CREATE ANY DATABASE; the dbcreator role)" }
    if ([int]$p.LoginExists -eq 0 -and [int]$p.CanCreateLogin -ne 1) { $lacking += "create the login [$AppAccount] (ALTER ANY LOGIN; the securityadmin role)" }
    if ([int]$p.DbExists -eq 1 -and [int]$p.ControlsDb -ne 1) { $lacking += "add the user and its roles in the existing database [$DbName] (CONTROL on it; db_owner)" }
    # Adding a member to dbcreator needs that role or sysadmin, and the msdb grant needs control of msdb.
    if ($BackupAccount) { $lacking += "give the backup account [$BackupAccount] dbcreator and its msdb grant (sysadmin)" }
    # Server-level settings on the database (recovery model, snapshot isolation) need ALTER on it, which an owner has.
}
if ($lacking.Count) {
    throw ("[$($p.RunAs)] can't provision Tide on [$SqlInstance]: it isn't sysadmin and can't " + ($lacking -join '; or ') +
           ". Nothing was changed. Have a DBA with sysadmin run this script (same -ConfigFile), or grant those roles " +
           "for the install. See docs/INSTALL.md.")
}
Write-Host "    Running as [$($p.RunAs)]$(if ([int]$p.IsSysadmin -eq 1) { ' (sysadmin)' }): permissions OK." -ForegroundColor Gray

$vars = @{
    DbName     = $DbName
    AppAccount = $AppAccount
    DataPath   = $(if ($DataPath) { $DataPath } else { '(default)' })   # sqlcmd won't take an empty -v value
    LogPath    = $(if ($LogPath) { $LogPath } else { '(default)' })
    SchemaMode = $SchemaMode
}
Invoke-Sql -InputFile $createSql -Vars $vars

if ($BackupAccount) {
    if (-not (Test-Path $backupSql)) { throw "Missing $backupSql" }
    Write-Host "==> Granting the backup account [$BackupAccount] what Backup-Tide.ps1 and Test-TideRestore.ps1 need" -ForegroundColor Cyan
    Invoke-Sql -InputFile $backupSql -Vars @{ DbName = $DbName; BackupAccount = $BackupAccount }
}

if ($SchemaMode -eq 'DbaApplies' -and $ApplySchema) {
    if (-not (Test-Path $schemaSql)) { throw "Missing $schemaSql (see deploy/README.md)" }
    Write-Host "==> Applying schema from $([System.IO.Path]::GetFileName($schemaSql))" -ForegroundColor Cyan
    if ($useModule) {
        Invoke-Sqlcmd -ServerInstance $SqlInstance -Database $DbName -InputFile $schemaSql `
                      @moduleTls -QueryTimeout 0 -OutputSqlErrors $true -AbortOnError -ErrorAction Stop
    } else {
        & sqlcmd.exe -S $SqlInstance -E -b @sqlcmdTrust -I -d $DbName -i $schemaSql   # -I: the schema has filtered indexes
        if ($LASTEXITCODE -ne 0) { throw "sqlcmd failed applying schema (exit $LASTEXITCODE)" }
    }
}

Write-Host "==> Database provisioning complete." -ForegroundColor Green
if ($SchemaMode -eq 'AppMigrates') {
    Write-Host "    The schema is created automatically on the app's first start (EF migrations)." -ForegroundColor Gray
}
